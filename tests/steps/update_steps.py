@given('an rfc-map.json file exists with code mappings')
def step_rfc_map_exists(context: Context):
    """
    Verify rfc-map.json exists (should be created by /rfc-generate in previous step).

    This step is now validation-only. The rfc-map.json file should have been
    automatically generated by the /rfc-generate command in the
    'an existing RFC document has been generated' step.
    """
    # Determine expected rfc-map.json path
    context.rfc_map_path = os.path.join(str(context.test_repo), 'docs', 'rfc-map.json')

    # Verify file was created by /rfc-generate
    assert os.path.exists(context.rfc_map_path), (
        f"rfc-map.json not found at {context.rfc_map_path}. "
        "It should have been generated by /rfc-generate command in previous step."
    )

    # Verify it contains valid JSON
    try:
        with open(context.rfc_map_path, 'r') as f:
            rfc_map = json.load(f)
    except json.JSONDecodeError as e:
        raise AssertionError(f"rfc-map.json contains invalid JSON: {e}")

    # Verify basic structure
    assert 'version' in rfc_map, "rfc-map.json missing 'version' field"
    assert 'mappings' in rfc_map, "rfc-map.json missing 'mappings' field"
    assert isinstance(rfc_map['mappings'], list), "rfc-map.json 'mappings' must be a list"

    # Verify it contains at least some mappings (not empty)
    assert len(rfc_map['mappings']) > 0, (
        "rfc-map.json contains no mappings. /rfc-generate should have created code-to-RFC mappings."
    )


