@when('I run "{command}"')
def step_run_update_command(context: Context, command: str):
    """Execute /rfc-update or /rfc-generate command using real implementation"""
    import sys
    from pathlib import Path

    # Add tests/support to sys.path for imports
    support_dir = Path(__file__).parent.parent / 'support'
    if str(support_dir) not in sys.path:
        sys.path.insert(0, str(support_dir))

    from command_runner import run_slash_command

    context.command = command

    # Check if Serena MCP availability was set in context
    serena_available = getattr(context, 'serena_mcp_available', True)

    # Execute command using real implementation
    result = run_slash_command(str(context.test_repo), command, serena_available=serena_available)

    # Store results in context
    context.command_exit_code = result.exit_code
    context.command_output = result.output + result.errors + result.warnings
    context.command_result = result

    # For /rfc-generate commands, also set context.generated_rfc
    if command.startswith('/rfc-generate'):
        if result.files_created:
            # Find the RFC file (not rfc-map.json)
            rfc_files = [f for f in result.files_created if f.endswith('.md')]
            if rfc_files:
                context.generated_rfc = rfc_files[0]
        else:
            # Fallback: infer from command
            docs_dir = os.path.join(str(context.test_repo), 'docs', 'generated')
            if '--output' in command:
                output_file = command.split('--output')[1].strip().split()[0]
            else:
                output_file = 'draft-generated-latest.md'
            context.generated_rfc = os.path.join(docs_dir, output_file)


