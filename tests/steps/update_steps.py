@when('I modify "{file_path}" method "{method_name}" signature')
def step_modify_method_signature(context: Context, file_path: str, method_name: str):
    """Simulate modifying a method signature"""
    full_path = os.path.join(str(context.test_repo), file_path)

    # Read existing file
    with open(full_path, 'r') as f:
        content = f.read()

    # Simulate signature change: add optional parameter 'c'
    if 'def add(self, a: float, b: float)' in content:
        modified_content = content.replace(
            'def add(self, a: float, b: float) -> float:',
            'def add(self, a: float, b: float, c: float = 0.0) -> float:'
        )
        modified_content = modified_content.replace(
            '"""Add two numbers"""',
            '"""Add two or three numbers"""'
        )
        modified_content = modified_content.replace(
            'return a + b',
            'return a + b + c'
        )

        with open(full_path, 'w') as f:
            f.write(modified_content)

        context.code_changed = True
        context.modified_file = file_path
        context.modified_method = method_name


