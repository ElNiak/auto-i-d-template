@given('an existing RFC document has been generated')
def step_existing_rfc_generated(context: Context):
    """Set up an existing RFC document for update tests with matching source code"""

    # ===== 1. CREATE SOURCE CODE FIRST =====
    # This is the code that the RFC will document
    src_dir = os.path.join(str(context.test_repo), 'src')
    os.makedirs(src_dir, exist_ok=True)

    calculator_py = os.path.join(src_dir, 'calculator.py')
    with open(calculator_py, 'w') as f:
        f.write('''"""
Calculator module for basic arithmetic operations
"""

class Calculator:
    """
    A simple calculator class

    Attributes:
        history: List of calculation operations performed
    """

    def __init__(self):
        """Initialize calculator with empty history"""
        self.history = []

    def add(self, a: float, b: float) -> float:
        """
        Add two numbers

        Args:
            a: First operand
            b: Second operand

        Returns:
            Sum of a and b
        """
        result = a + b
        self.history.append(('add', a, b, result))
        return result

    def subtract(self, a: float, b: float) -> float:
        """
        Subtract b from a

        Args:
            a: Minuend
            b: Subtrahend

        Returns:
            Difference of a minus b
        """
        result = a - b
        self.history.append(('subtract', a, b, result))
        return result
''')

    context.sample_code_file = calculator_py

    # ===== 2. NOW GENERATE RFC USING REAL /rfc-generate COMMAND =====
    # Import command runner
    import sys
    support_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'support')
    if support_dir not in sys.path:
        sys.path.insert(0, support_dir)

    from command_runner import run_slash_command

    # Run REAL /rfc-generate command to create RFC from source code
    result = run_slash_command(
        str(context.test_repo),
        '/rfc-generate src/ --output draft-calculator-00.md',
        serena_available=getattr(context, 'serena_mcp_available', True)
    )

    # Verify RFC generation succeeded
    assert result.exit_code == 0, f"RFC generation failed with exit code {result.exit_code}. Errors: {result.errors}"
    assert result.files_created, f"No files were created by /rfc-generate. Output: {result.output}"

    # Find the generated RFC file
    rfc_files = [f for f in result.files_created if f.endswith('.md') and 'draft-' in f]
    assert len(rfc_files) > 0, f"No RFC file generated. Files created: {result.files_created}"

    # Store RFC path for use in subsequent steps
    context.existing_rfc_path = rfc_files[0]

    # Verify RFC file actually exists on disk
    assert os.path.exists(context.existing_rfc_path), f"RFC file {context.existing_rfc_path} not found on disk"


